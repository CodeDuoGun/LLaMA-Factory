logger = logging.getLogger(__name__)


def parse_templates_from_text(text: str) -> list[dict[str, Any]]:
    """Parse txt generated by convert_template_to_txt.py into template records."""
    starts = [match.start() for match in re.finditer(r"^模板ID:\s*", text, flags=re.MULTILINE)]
    templates = []

    for index, start in enumerate(starts):
        end = starts[index + 1] if index + 1 < len(starts) else len(text)
        block = text[start:end]
        id_match = re.search(r"^模板ID:\s*(\S+)\s*$", block, flags=re.MULTILINE)
        name_match = re.search(r"^方剂名称:\s*(.+?)\s*$", block, flags=re.MULTILINE)
        if not id_match or not name_match:
            continue

        template_id_text = id_match.group(1).strip()
        template_id: int | str = int(template_id_text) if template_id_text.isdigit() else template_id_text
        drugs = []
        for line in block.splitlines():
            drug_match = re.match(
                r"^\s*\d+\.\s+(.+?)\s+([0-9.]+)\s*([^\s(（]+)\s*[\(（](.+?)[\)）]\s*$",
                line,
            )
            if not drug_match:
                continue
            drugs.append(
                {
                    "drug_name": drug_match.group(1).strip(),
                    "quantity": drug_match.group(2).strip(),
                    "unit": drug_match.group(3).strip(),
                    "drug_form": drug_match.group(4).strip(),
                }
            )

        templates.append(
            {
                "template_id": template_id,
                "template_name": name_match.group(1).strip(),
                "drugs": drugs,
                "source_text": block.strip(),
            }
        )

    return templates


def load_templates_from_txt(path: Path) -> list[dict[str, Any]]:
    return parse_templates_from_text(path.read_text(encoding="utf-8"))


def format_template(template: dict[str, Any]) -> str:
    drugs = "、".join(
        f"{drug.get('drug_name', '')}{drug.get('quantity', '')}{drug.get('unit', '')}({drug.get('drug_form', '')})"
        for drug in template.get("drugs", [])
        if drug.get("drug_name")
    )
    return f"模板ID: {template.get('template_id')}\n方剂名称: {template.get('template_name')}\n药物组成: {drugs}"


def chunk_items(items: list[dict[str, Any]], chunk_size: int) -> list[list[dict[str, Any]]]:
    if chunk_size <= 0:
        raise ValueError("chunk_size must be greater than 0")
    return [items[index : index + chunk_size] for index in range(0, len(items), chunk_size)]


