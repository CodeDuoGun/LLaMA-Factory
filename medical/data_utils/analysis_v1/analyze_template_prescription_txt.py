def extract_json_payload(response_text: str) -> str:
    text = response_text.strip()
    fenced = re.search(r"```(?:json)?\s*(.*?)```", text, flags=re.IGNORECASE | re.DOTALL)
    if fenced:
        text = fenced.group(1).strip()

    starts = [index for index in (text.find("{"), text.find("[")) if index != -1]
    if not starts:
        return text

    decoder = json.JSONDecoder()
    start = min(starts)
    _, end = decoder.raw_decode(text[start:])
    return text[start : start + end]


def parse_llm_json(response_text: str) -> dict[str, Any]:
    payload = extract_json_payload(response_text)
    parsed = json.loads(payload)
    if not isinstance(parsed, dict):
        raise ValueError("LLM response JSON must be an object")
    return parsed


def save_json(data: dict[str, Any], output_file: Path) -> None:
    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def analyze_file(
    input_file: Path,
    output_file: Path,
    llm_call: Callable[[str], str],
    chunk_size: int = 20,
    delay: float = 1.0,
) -> dict[str, Any]:
    templates = load_templates_from_txt(input_file)
    batches = chunk_items(templates, chunk_size)
    batch_analyses = []

    result: dict[str, Any] = {
        "metadata": {
            "input_file": str(input_file),
            "template_count": len(templates),
            "chunk_size": chunk_size,
            "batch_count": len(batches),
        },
        "templates": [
            {
                "template_id": template.get("template_id"),
                "template_name": template.get("template_name"),
                "drugs": template.get("drugs", []),
            }
            for template in templates
        ],
        "batch_analyses": batch_analyses,
        "final_analysis": {},
    }

    for index, batch in enumerate(batches, start=1):
        logger.info(f"Analyzing template batch {index}/{len(batches)}")
        response = llm_call(build_batch_prompt(batch, batch_index=index, total_batches=len(batches)))
        analysis = parse_llm_json(response)
        batch_analyses.append(
            {"batch_index": index, "template_ids": [item["template_id"] for item in batch], "analysis": analysis}
        )
        save_json(result, output_file)
        if delay > 0 and index < len(batches):
            time.sleep(delay)

    logger.info("Merging batch analyses")
    result["final_analysis"] = parse_llm_json(llm_call(build_merge_prompt(batch_analyses)))
    save_json(result, output_file)
    return result


def _config_value(name: str, default: str = "") -> str:
    value = getattr(config, name, default)
    return str(value) if value is not None else default


def create_llm_call(
    model: str | None = None, base_url: str | None = None, api_key: str | None = None
) -> Callable[[str], str]:
    from openai import OpenAI

    provider = _config_value("LLM_PROVIDER", "ark").lower()
    selected_model = model
    selected_base_url = base_url
    selected_api_key = api_key

    if not selected_base_url or not selected_api_key or not selected_model:
        if provider == "dashscope":
            selected_base_url = selected_base_url or _config_value("DASHSCOPE_BASE_URL")
            selected_api_key = selected_api_key or _config_value("DASHSCOPE_API_KEY")
            selected_model = selected_model or _config_value("QWEN_TEXT_MODEL", "qwen-plus")
        elif provider == "deepseek":
            selected_base_url = selected_base_url or _config_value("DEEPSEEK_BASE_URL")
            selected_api_key = selected_api_key or _config_value("DEEPSEEK_API_KEY")
            selected_model = selected_model or _config_value("DEEPSEEK_MODEL")
        elif provider == "baichuan":
            selected_base_url = selected_base_url or _config_value("BAICHUAN_BASE_URL")
            selected_api_key = selected_api_key or _config_value("BAICHUAN_API_KEY")
            selected_model = selected_model or _config_value("BAICHUAN_TEXT_MODEL")
        else:
            selected_base_url = selected_base_url or _config_value("ARK_BASE_URL")
            selected_api_key = selected_api_key or _config_value("ARK_API_KEY")
            selected_model = selected_model or _config_value("DOUBAO_TEXT_MODEL", DEFAULT_MODEL)

    if not selected_base_url:
        raise ValueError("LLM base_url is empty; set config or pass --base-url")
    if not selected_api_key:
        raise ValueError("LLM api_key is empty; set config or pass --api-key")
    if not selected_model:
        raise ValueError("LLM model is empty; set config or pass --model")

    client = OpenAI(api_key=selected_api_key, base_url=selected_base_url, timeout=(5.0, 120.0))

    def call(prompt: str) -> str:
        response = client.chat.completions.create(
            model=selected_model,
            messages=[{"role": "user", "content": prompt}],
            temperature=0,
        )
        return response.choices[0].message.content or "{}"

    logger.info(f"Using LLM provider={provider}, model={selected_model}")
    return call


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="调用 LLM 分析 wuweiping_template_prescription.txt 模板方。")
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT_FILE, help=f"输入 txt，默认 {DEFAULT_INPUT_FILE}")
    parser.add_argument(
        "--output", type=Path, default=DEFAULT_OUTPUT_FILE, help=f"输出 JSON，默认 {DEFAULT_OUTPUT_FILE}"
    )
    parser.add_argument("--chunk-size", type=int, default=20, help="每批发送给 LLM 的模板方数量，默认 20")
    parser.add_argument("--delay", type=float, default=1.0, help="批次请求间隔秒数，默认 1.0")
    parser.add_argument("--model", default=None, help="覆盖 config 中的 LLM 模型名")
    parser.add_argument("--base-url", default=None, help="覆盖 config 中的 OpenAI 兼容 base_url")
    parser.add_argument("--api-key", default=None, help="覆盖 config 中的 API key")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    llm_call = create_llm_call(model=args.model, base_url=args.base_url, api_key=args.api_key)
    result = analyze_file(args.input, args.output, llm_call, chunk_size=args.chunk_size, delay=args.delay)
    print(json.dumps(result["metadata"], ensure_ascii=False, indent=2))
    print(f"Saved to {args.output}")


if __name__ == "__main__":
    main()
