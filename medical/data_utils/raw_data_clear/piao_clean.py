DEFAULT_INPUT = PROJECT_ROOT / "medical/data/二期南区/doctor_677_朴炳奎"
DEFAULT_OUTPUT = PROJECT_ROOT / "medical/processed_data/doctor_677_朴炳奎"
BASE_URL = "https://dashscope.aliyuncs.com/compatible-mode/v1"
PDF_SUFFIX = ".pdf"
PIAO_IMAGE_PROMPT_PATH = PROJECT_ROOT / "medical/data_utils/prompts/piao_recordimg_clean.txt"
PIAO_MERGE_PROMPT_PATH = PROJECT_ROOT / "medical/data_utils/prompts/piao_record_merge_clean.txt"
IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg"}


def load_prompts() -> tuple[str, str]:
    """Read Piao's dedicated image-extraction and visit-merging prompts."""
    image_prompt = PIAO_IMAGE_PROMPT_PATH.read_text(encoding="utf-8").strip()
    merge_prompt = PIAO_MERGE_PROMPT_PATH.read_text(encoding="utf-8").strip()
    if not image_prompt or not merge_prompt:
        raise ValueError(f"朴老单图或合并提示词为空: {PIAO_IMAGE_PROMPT_PATH}, {PIAO_MERGE_PROMPT_PATH}")
    return image_prompt, merge_prompt


def read_existing_records(path: Path) -> list[dict[str, Any]]:
    """Read existing JSONL records so completed PDFs can be skipped or replaced."""
    if not path.is_file():
        return []
    records = []
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        record = json.loads(line)
        if not isinstance(record, dict):
            raise ValueError(f"JSONL 第 {line_number} 行不是对象: {path}")
        records.append(record)
    return records


def without_ai_fields(record: dict[str, Any]) -> dict[str, Any]:
    """Remove generated AI fields from a medical record."""
    return {key: value for key, value in record.items() if not key.startswith("ai_")}


def write_records_jsonl(path: Path, records: list[dict[str, Any]]) -> None:
    """Atomically replace the output JSONL with records that contain no ai_* fields."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", dir=path.parent, prefix=".medical_records_", suffix=".jsonl", delete=False
    ) as stream:
        temporary = Path(stream.name)
        for record in records:
            stream.write(json.dumps(without_ai_fields(record), ensure_ascii=False) + "\n")
    temporary.replace(path)


def record_belongs_to_pdf(record: dict[str, Any], pdf_path: Path) -> bool:
    """Match records generated by the current and previous Piao order_sn formats."""
    if record.get("source_pdf") == pdf_path.name:
        return True
    order_sn = record.get("order_sn")
    if not isinstance(order_sn, str):
        return False
    current_prefix = f"{pdf_path.stem}_"
    legacy_key = hashlib.sha256(pdf_path.name.encode("utf-8")).hexdigest()[:12]
    legacy_prefix = f"piao_{legacy_key}_"
    return order_sn.startswith(current_prefix) or order_sn.startswith(legacy_prefix)


def discover_pdf_paths(input_dir: Path, patient_root: Path) -> list[Path]:
    """Find top-level PDFs and PDFs already archived in same-name patient folders."""
    pdf_by_patient = {
        path.stem: path
        for path in input_dir.iterdir()
        if path.is_file() and path.suffix.lower() == PDF_SUFFIX
    }
    if patient_root.is_dir():
        for patient_dir in patient_root.iterdir():
            if not patient_dir.is_dir():
                continue
            for path in patient_dir.iterdir():
                if path.is_file() and path.suffix.lower() == PDF_SUFFIX and path.stem == patient_dir.name:
                    pdf_by_patient.setdefault(patient_dir.name, path)
    return sorted(pdf_by_patient.values(), key=lambda path: path.name.casefold())


def convert_pdfs_to_images(
    input_dir: Path,
    *,
    dpi: int,
    limit: int | None = None,
    pdf_paths: list[Path] | None = None,
    patient_root: Path | None = None,
    pdftoppm: str = "pdftoppm",
) -> dict[Path, list[Path]]:
    """Move each PDF into its patient folder and render pages under that folder's img/."""
    if pdf_paths is None:
        root = patient_root or input_dir
        pdf_paths = discover_pdf_paths(input_dir, root)
    if limit is not None:
        pdf_paths = pdf_paths[:limit]
    if not pdf_paths:
        raise ValueError(f"目录中没有 PDF 文件: {input_dir}")
    patient_root = patient_root or input_dir
    patient_root.mkdir(parents=True, exist_ok=True)
    images_by_pdf: dict[Path, list[Path]] = {}

    for pdf_path in pdf_paths:
        patient_dir = patient_root / pdf_path.stem
        patient_dir.mkdir(parents=True, exist_ok=True)
        patient_pdf = patient_dir / pdf_path.name
        if pdf_path.resolve() != patient_pdf.resolve():
            if patient_pdf.exists():
                if not filecmp.cmp(pdf_path, patient_pdf, shallow=False):
                    raise FileExistsError(f"同名患者文件夹中已有不同内容的 PDF，未覆盖: {patient_pdf}")
                pdf_path.unlink()
                logger.info(f"删除外层重复 PDF patient={patient_dir.name} pdf={pdf_path.name}")
            else:
                shutil.move(str(pdf_path), str(patient_pdf))
                logger.info(f"PDF 已移入患者文件夹 patient={patient_dir.name} pdf={patient_pdf.name}")
        pdf_path = patient_pdf

        image_dir = patient_dir / "img"
        image_dir.mkdir(parents=True, exist_ok=True)
        if any(image_dir.iterdir()):
            existing_images = sorted(
                (
                    path
                    for path in image_dir.iterdir()
                    if path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES and path.stem.isdigit()
                ),
                key=lambda path: int(path.stem),
            )
            if not existing_images:
                raise ValueError(f"图片目录非空但没有序号图片，无法清洗: {image_dir}")
            images_by_pdf[pdf_path] = existing_images
            logger.info(
                f"复用已有图片 patient={patient_dir.name} images={len(existing_images)} image_dir={image_dir}"
            )
            continue

        if shutil.which(pdftoppm) is None:
            raise RuntimeError(f"找不到 PDF 转图工具 {pdftoppm!r}，请安装 Poppler 或通过 --pdftoppm 指定可执行文件")
        manifest: list[dict[str, Any]] = []
        with tempfile.TemporaryDirectory(prefix="piao_pdf_", dir=image_dir) as temporary_dir:
            prefix = Path(temporary_dir) / "page"
            result = subprocess.run(
                [pdftoppm, "-q", "-png", "-r", str(dpi), str(patient_pdf), str(prefix)],
                check=False,
                capture_output=True,
                text=True,
            )
            if result.returncode:
                detail = result.stderr.strip() or result.stdout.strip()
                raise RuntimeError(f"PDF 转图失败: {pdf_path.name}: {detail}")

            rendered_pages = sorted(
                Path(temporary_dir).glob("page-*.png"),
                key=lambda path: int(path.stem.rsplit("-", 1)[1]),
            )
            if not rendered_pages:
                raise RuntimeError(f"PDF 未生成页面图片: {pdf_path}")

            pdf_images: list[Path] = []
            for page_number, page_path in enumerate(rendered_pages, start=1):
                image_path = image_dir / f"{page_number:06d}.png"
                page_path.replace(image_path)
                pdf_images.append(image_path)
                manifest.append(
                    {
                        "sequence": page_number,
                        "image": image_path.name,
                        "source_pdf": pdf_path.name,
                        "page": page_number,
                    }
                )
            images_by_pdf[pdf_path] = pdf_images
        current_images = {path.name for path in images_by_pdf[pdf_path]}
        for old_image in image_dir.glob("*.png"):
            if old_image.stem.isdigit() and old_image.name not in current_images:
                old_image.unlink()
        manifest_path = image_dir / "manifest.json"
        temporary_manifest = image_dir / ".manifest.json.tmp"
        temporary_manifest.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        temporary_manifest.replace(manifest_path)
        logger.info(
            f"PDF 转图完成 patient={patient_dir.name} pdf={patient_pdf} "
            f"pages={len(images_by_pdf[pdf_path])} image_dir={image_dir}"
        )

    image_count = sum(len(images) for images in images_by_pdf.values())
    logger.info(f"PDF 转图全部完成 pdfs={len(pdf_paths)} images={image_count} patient_root={patient_root}")
    return images_by_pdf


def make_record(item: dict[str, Any], source_pdf: Path, visit_order: int, doctor_name: str) -> dict[str, Any]:
    """Map one structured visit to the existing schema using PDF name and visit date as its order number."""
    record = {
        key: value
        for key, value in build_record(item, "", visit_order).items()
        if not key.startswith("ai_")
    }
    visit_date = str(record.get("see_doc_time") or "").strip()
    date_match = re.search(r"(\d{4})\D+(\d{1,2})\D+(\d{1,2})", visit_date)
    if date_match:
        date_key = f"{date_match.group(1)}-{int(date_match.group(2)):02d}-{int(date_match.group(3)):02d}"
    else:
        date_key = re.sub(r"[^0-9A-Za-z-]", "", visit_date) or f"undated-{visit_order:03d}"
    order_sn = f"{source_pdf.stem}_{date_key}"
    record["patient_id"] = source_pdf.stem
    record["order_sn"] = order_sn
    record["doctor_name"] = doctor_name
    record["doctor_id"] = 677 
    for prescription_index, prescription in enumerate(record["ps"], start=1):
        prescription["order_sn"] = order_sn
        prescription["prescription_order_id"] = f"{order_sn}_p{prescription_index:02d}"
    return record


def parse_args() -> argparse.Namespace:
    from dotenv import dotenv_values

    model_from_file = dotenv_values(PROJECT_ROOT / ".env").get("MEDICAL_AGENT_MODEL")
    default_model = model_from_file or os.getenv("MEDICAL_AGENT_MODEL", "")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", type=Path, default=DEFAULT_INPUT, help="PDF 所在目录")
    parser.add_argument("--patient-root", type=Path, help="患者文件夹根目录；默认使用 PDF 所在目录")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--limit", type=int, help="最多处理排序后的前 N 个 PDF")
    parser.add_argument("--reclean", action="store_true", help="重新清洗已处理患者，并替换 JSONL 中对应的旧记录")
    parser.add_argument("--doctor-name", default="朴炳奎")
    parser.add_argument("--vision-model", default=default_model)
    parser.add_argument("--text-model", default=default_model)
    parser.add_argument("--base-url", default=os.getenv("DASHSCOPE_BASE_URL", BASE_URL))
    parser.add_argument("--pdftoppm", default="pdftoppm", help="Poppler 的 pdftoppm 可执行文件")
    parser.add_argument("--dpi", type=int, default=200)
    parser.add_argument("--concurrency", type=int, default=4)
    parser.add_argument("--timeout", type=float, default=120)
    parser.add_argument("--retries", type=int, default=2)
    return parser.parse_args()


async def run(args: argparse.Namespace) -> int:
    if args.concurrency < 1 or args.retries < 0 or args.timeout <= 0 or args.dpi < 1:
        raise ValueError("concurrency、timeout 和 dpi 必须为正数，retries 不能为负数")
    if args.limit is not None and args.limit < 1:
        raise ValueError("limit 必须为正整数")

    target = args.output_dir / "medical_records_ai.jsonl"
    existing_records = read_existing_records(target)
    patient_root = args.patient_root or args.input_dir
    pdf_paths = discover_pdf_paths(args.input_dir, patient_root)
    if args.limit is not None:
        pdf_paths = pdf_paths[: args.limit]
    if not pdf_paths:
        raise ValueError(f"目录中没有可处理的 PDF 文件: {args.input_dir}")

    if not args.reclean:
        skipped_pdfs = [
            pdf_path
            for pdf_path in pdf_paths
            if any(record_belongs_to_pdf(record, pdf_path) for record in existing_records)
        ]
        if skipped_pdfs:
            logger.info(f"跳过已清洗患者 count={len(skipped_pdfs)}，如需重跑请指定 --reclean")
        skipped_names = {pdf_path.name for pdf_path in skipped_pdfs}
        pdf_paths = [pdf_path for pdf_path in pdf_paths if pdf_path.name not in skipped_names]
        if not pdf_paths:
            write_records_jsonl(target, existing_records)
            logger.info("所选 PDF 均已清洗，无需处理")
            return 0

    if not args.vision_model or not args.text_model:
        raise ValueError("请在 .env 中设置 MEDICAL_AGENT_MODEL，或通过 --vision-model 和 --text-model 指定模型")
    api_key = os.getenv("DASHSCOPE_API_KEY")
    if not api_key:
        raise ValueError("请设置 DASHSCOPE_API_KEY")
    from medical.data_utils.structured_agent import AgentModelConfig, StructuredAgent

    images_by_pdf = convert_pdfs_to_images(
        args.input_dir,
        dpi=args.dpi,
        pdf_paths=pdf_paths,
        patient_root=args.patient_root,
        pdftoppm=args.pdftoppm,
    )
    image_prompt, merge_prompt = load_prompts()
    image_prompt = image_prompt.replace("朴炳奎", args.doctor_name)
    merge_prompt = merge_prompt.replace("朴炳奎", args.doctor_name)

    def make_config(model: str, name: str, *, streaming: bool) -> AgentModelConfig:
        config = AgentModelConfig(
            model=model,
            api_key=api_key,
            base_url=args.base_url,
            temperature=0,
            thinking=False,
            timeout=args.timeout,
            max_retries=0,
            client_kwargs={"streaming": streaming},
        )
        logger.info(
            f"模型参数 agent={name} model={config.model} base_url={config.base_url} "
            f"temperature={config.temperature} thinking={config.thinking} streaming={streaming} "
            f"timeout={config.timeout} max_retries={config.max_retries} validation_retries=1"
        )
        return config

    image_config = make_config(args.vision_model, "piao_image_extractor", streaming=False)
    merge_config = make_config(args.text_model, "piao_visit_merger", streaming=True)
    image_agent = TextExtractionAgent(image_config.build(), image_prompt)
    merge_agent = StructuredAgent.from_config(
        merge_config,
        MergedVisits,
        system_prompt=merge_prompt,
        name="piao_visit_merger",
        output_mode="json_object",
        validation_retries=1,
    )
    semaphore = asyncio.Semaphore(args.concurrency)
    all_images = [image for pdf_images in images_by_pdf.values() for image in pdf_images]
    logger.info(
        f"开始朴老病历单图提取 pdfs={len(images_by_pdf)} images={len(all_images)} "
        f"concurrency={args.concurrency} vision_model={args.vision_model} text_model={args.text_model}"
    )

    async def limited_extract(path: Path) -> dict[str, Any]:
        async with semaphore:
            return await extract_image(image_agent, path, args.retries)

    extraction_results = await asyncio.gather(
        *(limited_extract(image_path) for image_path in all_images),
        return_exceptions=True,
    )
    extraction_failures = [
        (image_path, result)
        for image_path, result in zip(all_images, extraction_results)
        if isinstance(result, Exception)
    ]
    if extraction_failures:
        for image_path, error in extraction_failures:
            logger.error(f"单图解析失败 image={image_path.name}: {type(error).__name__}: {error}")
        logger.error(f"单图解析失败 images={len(extraction_failures)}/{len(all_images)}，未生成最终 JSONL")
        return 1

    extracted_by_path = dict(zip(all_images, extraction_results))
    logger.info("单图提取全部完成，开始按 PDF 分组生成时间窗口病史及处方")

    async def merge_pdf(pdf_path: Path, pdf_images: list[Path]) -> list[dict[str, Any]]:
        extracted = [extracted_by_path[image_path] for image_path in pdf_images]
        async with semaphore:
            merged = await call_model(
                merge_agent,
                json.dumps(
                    {"source_pdf": pdf_path.name, "images": extracted},
                    ensure_ascii=False,
                ),
                args.retries,
            )
        if not isinstance(merged, dict) or not isinstance(merged.get("items"), list):
            raise ValueError(f"合并结果必须为包含 items 数组的 JSON 对象: {pdf_path.name}")
        if any(not isinstance(item, dict) for item in merged["items"]):
            raise ValueError(f"items 中存在非对象: {pdf_path.name}")
        records = [
            make_record(item, pdf_path, visit_order, args.doctor_name)
            for visit_order, item in enumerate(merged["items"], start=1)
        ]
        logger.info(f"PDF 病史结构化完成 pdf={pdf_path.name} images={len(pdf_images)} visits={len(records)}")
        return records

    pdf_paths = list(images_by_pdf)
    merge_results = await asyncio.gather(
        *(merge_pdf(pdf_path, images_by_pdf[pdf_path]) for pdf_path in pdf_paths),
        return_exceptions=True,
    )
    merge_failures = [
        (pdf_path, result) for pdf_path, result in zip(pdf_paths, merge_results) if isinstance(result, Exception)
    ]
    if merge_failures:
        for pdf_path, error in merge_failures:
            logger.error(f"病史合并失败 pdf={pdf_path.name}: {type(error).__name__}: {error}")
        logger.error(f"病史合并失败 pdfs={len(merge_failures)}/{len(pdf_paths)}，未覆盖最终 JSONL")
        return 1

    replaced_record_count = sum(
        1
        for record in existing_records
        if any(record_belongs_to_pdf(record, pdf_path) for pdf_path in pdf_paths)
    )
    preserved_records = [
        record
        for record in existing_records
        if not any(record_belongs_to_pdf(record, pdf_path) for pdf_path in pdf_paths)
    ]
    updated_records = preserved_records + [record for pdf_records in merge_results for record in pdf_records]
    write_records_jsonl(target, updated_records)
    record_count = sum(len(records) for records in merge_results)
    logger.info(
        f"病历写入完成 path={target} pdfs={len(pdf_paths)} records={record_count} "
        f"replaced_records={replaced_record_count} preserved_records={len(preserved_records)}"
    )
    return 0


def main() -> None:
    from dotenv import load_dotenv

    load_dotenv(PROJECT_ROOT / ".env")
    raise SystemExit(asyncio.run(run(parse_args())))


if __name__ == "__main__":
    main()
